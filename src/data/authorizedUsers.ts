const getThaiInitials = (fullName: string): string => {
  const cleaned = fullName
    .replace(/^(น\.ส\.|นางสาว|นาง|นาย|สิบเอก|ดร\.)\s*/g, '')
    .trim();
  const parts = cleaned.split(/\s+/);
  const first = parts[0]?.[0] || '';
  const second = parts[1]?.[0] || parts[0]?.[1] || '';
  return (first + second) || 'จน';
};

